let gpu: Ed25519GPU | null = null;
afterAll(() => { gpu?.destroy(); gpu = null; });
async function getGpu(): Promise<Ed25519GPU> {
    if (!gpu) gpu = await Ed25519GPU.create();
    return gpu;
}

describe('RFC 8032 §6.1 — Ed25519 test vectors', () => {
    it('derives exact public keys for all 4 vectors', async () => {
        const g      = await getGpu();
        const seeds  = VECTORS.map(v => v.seed);
        const pubkeys = await g.derivePublicKeys(seeds);
        for (let i = 0; i < VECTORS.length; i++) {
            expect(pubkeys[i], VECTORS[i].label).toEqual(VECTORS[i].pubkey);
        }
    }, 120_000);
});
